export const DICTIONARIES: Record<Language, Record<Key, string>> = { en, it }

let current: Language = 'en'

export function setLanguage(lang: Language) {
  current = lang
}

export function getLanguage(): Language {
  return current
}

/** "system" follows the first macOS preferred language we support, else English. */
export function resolveLanguage(pref: LanguagePref | undefined, systemLocales: readonly string[]): Language {
  if (pref === 'en' || pref === 'it') return pref
  for (const l of systemLocales) {
    const base = l.toLowerCase().split(/[-_]/)[0]
    if (base === 'en' || base === 'it') return base
  }
  return 'en'
}

const fill = (s: string, vars?: Record<string, string | number>) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s)

export function t(key: Key, vars?: Record<string, string | number>, lang: Language = current): string {
  return fill(DICTIONARIES[lang]?.[key] ?? en[key] ?? key, vars)
}

type PluralBase = { [K in Key]: K extends `${infer B}_one` ? B : never }[Key]

/** Plural-aware lookup: picks `<base>_one` or `<base>_other` and fills {n} with a localized number. */
export function tn(base: PluralBase, n: number, lang: Language = current): string {
  const key = (new Intl.PluralRules(lang).select(n) === 'one' ? `${base}_one` : `${base}_other`) as Key
  return t(key, { n: n.toLocaleString(lang) }, lang)
}

export function commandName(id: string, english: string, lang: Language = current): string {
  return lang === 'it' ? COMMAND_NAMES_IT[id] ?? english : english
}
